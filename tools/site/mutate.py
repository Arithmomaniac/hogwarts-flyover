def copy_worktree(target):
    for folder in ("src", "tools"):
        shutil.copytree(ROOT / folder, target / folder, ignore=shutil.ignore_patterns("__pycache__"))
    for rel in COPIED:
        (target / rel).parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(ROOT / rel, target / rel)


def check(m, mutate=True):
    """'fail' or 'pass': the mutation's tests in a fresh copy of the worktree, mutated unless `mutate` is False. A
    mutation that re-pins a source gets its own state folder, whose input locations start as this machine's, so the
    re-pinned copy never touches the shared cache; the unmutated copy keeps the machine's pins. A mutation that
    rebuilds a site's data runs the whole pipeline in the copy (a minute or two). Tests under tools/ run from the copy's
    root, the others from its src."""
    with tempfile.TemporaryDirectory(prefix="hog-site-mutate-") as folder:
        root = Path(folder)
        copy_worktree(root)
        source = root / m.file
        text = source.read_text(encoding="utf-8")
        if text.count(m.old) != 1:
            raise ValueError(f"{m.name}: the text to mutate occurs {text.count(m.old)} times in {m.file}")
        if mutate:
            source.write_text(text.replace(m.old, m.new), encoding="utf-8", newline="\n")
        env = dict(os.environ)
        if m.repin and mutate:
            state = root / "state"
            state.mkdir()
            shutil.copy2(machine_file(), state / "inputs.json")
            env["HOG_STATE_DIR"] = str(state)
            pinned = subprocess.run([sys.executable, "-X", "utf8", "-m", "tools.site.sources", "pin", m.repin],
                                    cwd=root, env=env, capture_output=True, text=True)
            if pinned.returncode:
                raise RuntimeError(f"{m.name}: re-pinning {m.repin} failed:\n{pinned.stderr[-2000:]}")
        if m.rebuild:
            script = f"from tools.site import build; build.build({m.rebuild!r})"
            built = subprocess.run([sys.executable, "-X", "utf8", "-c", script], cwd=root, env=env, capture_output=True,
                                   text=True)
            if built.returncode:
                raise RuntimeError(f"{m.name}: building {m.rebuild} failed:\n{built.stderr[-2000:]}")
        cwd = root if all(t.startswith("tools.") for t in m.tests) else root / "src"
        result = subprocess.run([sys.executable, "-X", "utf8", "-m", "unittest", *m.tests], cwd=cwd, env=env,
                                capture_output=True, text=True)
        return "fail" if result.returncode else "pass"


def main(argv):
    clean, bad = {}, 0
    with locks.heavy("site mutation checks (tools.site.mutate)"):
        for m in MUTATIONS:
            if argv and not any(a in m.name for a in argv):
                continue
            key = (m.tests, m.rebuild)
            if key not in clean:
                clean[key] = check(m, mutate=False)
            verdict = ("caught" if check(m) == "fail" else "SURVIVED") if clean[key] == "pass" else \
                "INVALID (its tests fail without the mutation)"
            bad += verdict != "caught"
            print(f"{m.name}: {verdict}", flush=True)
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
